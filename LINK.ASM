INICIO:
    MOV AX, @DATA
    MOV DS, AX

    MOV AX, 0013h
    INT 10h

    CALL CONFIGURAR_PALETA
    CALL LIMPIAR_PANTALLA

;====================================================================
; BUCLE PRINCIPAL
;====================================================================
BUCLE_PRINCIPAL:
    CALL ESPERAR_VRETRACE
    CALL LIMPIAR_AREA_SPRITE
    CALL DIBUJAR_SPRITE_ONDA

    MOV AX, WAVE_OFFSET
    INC AX
    AND AX, 31
    MOV WAVE_OFFSET, AX

    MOV AH, 01h
    INT 16h
    JZ BUCLE_PRINCIPAL

    MOV AH, 00h
    INT 16h

    MOV AX, 0003h
    INT 10h

    MOV AX, 4C00h
    INT 21h

;====================================================================
; PROCEDIMIENTOS
