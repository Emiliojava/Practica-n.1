;--------------------------------------------------------------------
CONFIGURAR_PALETA PROC
    PUSH AX
    PUSH CX
    PUSH DX
    PUSH SI

    LEA SI, PALETA
    MOV CX, 16
    MOV DX, 03C8h
    MOV AL, 0
    OUT DX, AL
    MOV DX, 03C9h

@@LP:
    LODSB
    OUT DX, AL
    LODSB
    OUT DX, AL
    LODSB
    OUT DX, AL
    LOOP @@LP

    POP SI
    POP DX
    POP CX
    POP AX
    RET
CONFIGURAR_PALETA ENDP

;--------------------------------------------------------------------
LIMPIAR_PANTALLA PROC
    PUSH AX
    PUSH CX
    PUSH DI
    PUSH ES

    MOV AX, VGA_SEG
    MOV ES, AX
    XOR DI, DI
    MOV AL, BG_COLOR
    MOV AH, AL
    MOV CX, 32000
    REP STOSW

    POP ES
    POP DI
    POP CX
    POP AX
    RET
LIMPIAR_PANTALLA ENDP

;--------------------------------------------------------------------
LIMPIAR_AREA_SPRITE PROC
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH DI
    PUSH ES

    MOV AX, VGA_SEG
    MOV ES, AX

    MOV AX, SPRITE_Y
    MOV BX, SCREEN_W
    MUL BX
    ADD AX, CLEAR_X
    MOV DI, AX

    MOV DX, CLEAR_H
    MOV AL, BG_COLOR

@@CR:
    PUSH DI
    MOV CX, CLEAR_W
    REP STOSB
    POP DI
    ADD DI, SCREEN_W
    DEC DX
    JNZ @@CR

    POP ES
    POP DI
    POP DX
    POP CX
    POP BX
    POP AX
    RET
LIMPIAR_AREA_SPRITE ENDP

;--------------------------------------------------------------------
ESPERAR_VRETRACE PROC
    PUSH AX
    PUSH DX
    MOV DX, 03DAh
@@W1:
    IN AL, DX
    TEST AL, 08h
    JNZ @@W1
@@W2:
    IN AL, DX
    TEST AL, 08h
    JZ @@W2
    POP DX
    POP AX
    RET
ESPERAR_VRETRACE ENDP

;--------------------------------------------------------------------
; DIBUJAR_SPRITE_ONDA
; Dibuja sprite escalado PIXEL_SIZE con desplazamiento sinusoidal.
;--------------------------------------------------------------------
DIBUJAR_SPRITE_ONDA PROC
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH DI
    PUSH ES

    MOV AX, VGA_SEG
    MOV ES, AX

    LEA SI, SPRITE
    MOV CUR_ROW, 0

@@FILA:
    ;--- Obtener desplazamiento seno ---
    MOV BX, CUR_ROW
    ADD BX, WAVE_OFFSET
    AND BX, 31
    LEA DI, SINETAB
    MOV AL, [DI+BX]
    CBW
    MOV CUR_DESP, AX

    ;--- Calcular Y base ---
    MOV AX, CUR_ROW
    MOV BX, PIXEL_SIZE
    MUL BX
    ADD AX, SPRITE_Y
    MOV CUR_Y, AX

    ;--- Repetir PIXEL_SIZE lineas ---
    MOV DX, PIXEL_SIZE

@@REP_V:
    PUSH DX
    PUSH SI                      ; guardar inicio fila

    ;--- Offset de linea = CUR_Y * 320 ---
    MOV AX, CUR_Y
    MOV BX, SCREEN_W
    MUL BX
    MOV LINE_OFF, AX

    ;--- Recorrer columnas ---
    XOR BX, BX                   ; columna = 0
    MOV CX, SPRITE_W

@@COL:
    MOV AL, [SI]                 ; color del pixel
    CMP AL, BG_COLOR
    JE @@SKIP

    ;--- Calcular X = col*3 + SPRITE_X + desplazamiento ---
    PUSH AX                      ; guardar color
    MOV AX, BX
    MOV DX, AX
    SHL AX, 1
    ADD AX, DX                   ; AX = col * 3
    ADD AX, SPRITE_X
    ADD AX, CUR_DESP

    ;--- Limites ---
    CMP AX, 0
    JL @@SKIP2
    CMP AX, SCREEN_W - PIXEL_SIZE
    JG @@SKIP2

    ;--- Dibujar bloque horizontal de PIXEL_SIZE ---
    MOV DI, LINE_OFF
    ADD DI, AX                   ; DI = offset del pixel en VGA
    POP AX                       ; recuperar color (AL)

    ; Escribir PIXEL_SIZE bytes
    MOV ES:[DI], AL
    MOV ES:[DI+1], AL
    MOV ES:[DI+2], AL
    JMP @@SKIP

@@SKIP2:
    POP AX                       ; limpiar stack (color guardado)

@@SKIP:
    INC SI
    INC BX
    DEC CX
    JNZ @@COL

    POP SI                       ; restaurar inicio fila
    INC CUR_Y
    POP DX
    DEC DX
    JNZ @@REP_V

    ;--- Siguiente fila del sprite ---
    ADD SI, SPRITE_W
    INC CUR_ROW
    CMP CUR_ROW, SPRITE_H
    JB @@FILA

    POP ES
    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX
    RET
DIBUJAR_SPRITE_ONDA ENDP

